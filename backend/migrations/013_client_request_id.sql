-- 013_client_request_id.sql
--
-- Duplicate-safe registration (v2 user flow: "duplicate-safe client UUID").
--
-- Onboarding a farmer happens on a field connection. The request can take
-- long enough that the agent taps again, or the connection drops after the
-- server has committed but before the response arrives — and then the offline
-- queue retries it. Both produce TWO farmer records for one person: same
-- name, same NIN, two ids, two credit scores, and a cooperative member count
-- that is wrong. Nothing in the schema prevented it (`nin` is not unique, and
-- it is optional anyway).
--
-- The fix is an idempotency key the CLIENT generates once per form session
-- and resends on every retry. The server stores it; a second request with the
-- same key returns the farmer that already exists instead of creating
-- another.
--
-- Why a unique index rather than a check-then-insert: the check-then-insert
-- races. Two retries can both read "no such farmer" before either writes. The
-- index makes the second INSERT fail with 23505, which the controller catches
-- and turns into "here is the one that exists" — correct under concurrency
-- rather than merely usually correct.
--
-- Nullable, and only unique among non-null values: existing rows have no key,
-- and a client that sends none still works exactly as before. The column is
-- deliberately not a primary or foreign key — it is a client-chosen value and
-- nothing should reference it.

ALTER TABLE public.farmers
  ADD COLUMN IF NOT EXISTS client_request_id UUID;

CREATE UNIQUE INDEX IF NOT EXISTS uq_farmers_client_request_id
  ON public.farmers(client_request_id)
  WHERE client_request_id IS NOT NULL;

COMMENT ON COLUMN public.farmers.client_request_id IS
  'Idempotency key generated by the mobile app, one per onboarding form '
  'session. A repeat submission (double tap, retried offline sync, response '
  'lost after commit) carries the same value and returns the existing farmer '
  'instead of creating a second record. Nullable: a client that sends none '
  'behaves as before.';

-- Cooperatives have the same exposure, and the consequence is worse: a
-- duplicate cooperative splits its members across two records, so neither
-- one's average credit score is right. `registration_number` is already
-- unique, but it is OPTIONAL — a cooperative registered without one has no
-- protection at all.
ALTER TABLE public.cooperatives
  ADD COLUMN IF NOT EXISTS client_request_id UUID;

CREATE UNIQUE INDEX IF NOT EXISTS uq_cooperatives_client_request_id
  ON public.cooperatives(client_request_id)
  WHERE client_request_id IS NOT NULL;

COMMENT ON COLUMN public.cooperatives.client_request_id IS
  'Idempotency key generated by the mobile app, one per registration form '
  'session. See farmers.client_request_id. Matters more here than for '
  'farmers: a duplicate cooperative splits its members across two records, '
  'so neither average credit score is correct.';
